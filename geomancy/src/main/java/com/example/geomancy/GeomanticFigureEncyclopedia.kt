/**
 * Entrée d'encyclopédie pour une figure géomantique.
 * Associe systématiquement le nom ouest-africain au nom arabe (entre parenthèses)
 * pour garantir une terminologie unifiée et pédagogique pour les débutants.
 */
data class FigureEncyclopediaEntry(
  val id: Int,
  val code: String,
  val westAfricanName: String,
  val arabicName: String,
  val transliteration: String,
  val binaryStructure: String,
  val element: Element,
  val planet: Planet,
  val motion: FigureMotion,
  val polarity: FortunePolarity,
  val abjadValue: Int,
  val symbolicMeaning: String,
  val simpleExplanation: String,
  val detailedDescription: String,
  val housesInterpretation: Map<Int, String>,
  val color: String,
  val animal: String,
  val timingSpeed: String,
  val favorableDays: List<String>,
) {
  /** Nom unifié pour l'affichage : "NomOuestAfricain (NomArabe)" */
  val unifiedName: String
    get() = "$westAfricanName ($arabicName)"

  /** Représentation visuelle de la figure (4 rangs, de haut en bas) */
  val visualRepresentation: String
    get() = code.map { if (it == '1') "•" else "••" }.joinToString("\n")

  /** Représentation textuelle simplifiée pour les débutants */
  val beginnerFriendlyName: String
    get() = "$westAfricanName (appelée $arabicName en arabe)"
}

