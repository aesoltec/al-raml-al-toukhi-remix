/**
 * Classe de modèle pour gérer des leçons interactives avec terminologie unifiée.
 * Associe systématiquement le nom ouest-africain au nom arabe (entre parenthèses).
 */
data class InteractiveLesson(
  val id: String,
  val title: String,
  val arabicTitle: String,
  val level: Int,
  val content: String,
  val figures: List<Int> = emptyList(),
  val examples: List<String> = emptyList(),
  val exercises: List<String> = emptyList(),
  val visualAids: List<String> = emptyList(),
) {
  /** Titre unifié : "Titre Français (Titre Arabe)" */
  val unifiedTitle: String
    get() = "$title ($arabicTitle)"

  /** Contenu avec les noms de figures unifiés */
  val unifiedContent: String
    get() = content.replace(Regex("\\b([A-Z][a-z]+)\\b")) { match ->
      val name = match.value
      val entry = GeomanticFigureEncyclopedia.findByWestAfricanName(name)
      if (entry != null) "${entry.westAfricanName} (${entry.arabicName})" else name
    }

  /** Figures référencées dans la leçon */
  val referencedFigures: List<FigureEncyclopediaEntry>
    get() = figures.mapNotNull { GeomanticFigureEncyclopedia.findById(it) }
}

/**
 * Gestionnaire de leçons interactives avec terminologie unifiée.
 */
object InteractiveLessonManager {
  val lessons: List<InteractiveLesson> = emptyList()

  fun getLesson(id: String): InteractiveLesson? = lessons.find { it.id == id }
  fun getLessonsByLevel(level: Int): List<InteractiveLesson> = lessons.filter { it.level == level }
  fun getAllLessons(): List<InteractiveLesson> = lessons
}
